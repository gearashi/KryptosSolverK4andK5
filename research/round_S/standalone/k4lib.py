# The twelve additive conventions: plaintext alphabet, ciphertext alphabet, equation.
# key index k (0..25) is defined by   vig: c = p + k   beau: c = k - p   var: c = p - k   (indices in the named alphabets)
def conventions():
    out = []
    for pa_name, pa in (("std", STD), ("kry", KRY)):
        for ca_name, ca in (("std", STD), ("kry", KRY)):
            for eq in ("vig", "beau", "var"):
                out.append((f"P{pa_name}/C{ca_name}/{eq}", pa, ca, eq))
    return out

def key_index(p, c, pa, ca, eq):
    a, b = pa.index(p), ca.index(c)
    return {"vig": (b - a) % 26, "beau": (b + a) % 26, "var": (a - b) % 26}[eq]

def decrypt_index(c, k, pa, ca, eq):
    b = ca.index(c)
    return pa[{"vig": (b - k) % 26, "beau": (k - b) % 26, "var": (b + k) % 26}[eq]]

def encrypt_index(p, k, pa, ca, eq):
    a = pa.index(p)
    return ca[{"vig": (a + k) % 26, "beau": (k - a) % 26, "var": (a - k) % 26}[eq]]

def key_stream(pa, ca, eq):
    """dict zero-based position -> key index, at the 24 known positions (in-place assumption)."""
    return {i: key_index(PLAIN[i], C4[i], pa, ca, eq) for i in KNOWN}

def crib_ok(plain):
    return all(plain[i] == PLAIN[i] for i in KNOWN)
